"""Build the IT-scene five-state runtime assets.
The approved character design is unchanged; poses show her seated at a work desk.
Source sheet: outputs/whale-it-states/it-states-white.png (white background),
split by scripts/split-frames.py into outputs/whale-it-states/frames.
"""
from pathlib import Path
from hashlib import sha256
import json, base64, re
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
WORKSPACE = ROOT.parent
SHEET = WORKSPACE / 'outputs' / 'whale-it-states' / 'it-states-seated-white.png'
FRAMES = WORKSPACE / 'outputs' / 'whale-it-states' / 'frames-seated'
APPROVED = WORKSPACE / 'outputs' / 'whale-relock' / 'mini-three-views.png'
ASSETS = ROOT / 'assets'
PHASES = ['idle', 'running', 'waiting', 'done', 'error']
ID = 'whale-it-seated-v1'
PAGE = (288, 432)


def digest(path): return sha256(path.read_bytes()).hexdigest()


def palette(im, colors=160): return im.quantize(colors=colors, method=Image.Quantize.FASTOCTREE)


def write_asset(im, path):
    palette(im).save(path, optimize=True)
    saved = Image.open(path).convert('RGBA')
    assert saved.getpixel((0, 0))[3] == 0, path
    assert saved.getpixel((saved.width - 1, saved.height - 1))[3] == 0, path
    return {'sha256': digest(path), 'bytes': path.stat().st_size, 'size': list(saved.size)}


def main():
    frames = {}
    for phase in PHASES:
        src = FRAMES / f'{phase}-384.png'
        im = Image.open(src).convert('RGBA')
        assert im.size == (384, 576), (phase, im.size)
        # The page sprite is displayed at 176–282 px tall; 288 × 432 keeps it
        # above 1.5× for the largest size while cutting the inline payload.
        im = im.resize(PAGE, Image.Resampling.LANCZOS)
        box = im.getchannel('A').getbbox()
        assert box, phase
        assert box[1] > 3 and box[3] < PAGE[1] - 3, f'{phase} risks clipping head or shoes'
        frames[phase] = im

    manifest = {
        'id': ID,
        'approvedSource': 'outputs/whale-relock/mini-three-views.png',
        'forms': ['child'],
        'poseSheet': 'outputs/whale-it-states/it-states-seated-white.png',
        'approvedSha256': digest(APPROVED),
        'sheetSha256': digest(SHEET),
        'model': 'gpt-image-2.6-sunburst',
        'canvas': list(PAGE),
        'states': {},
    }

    sprites, icons = {}, {}
    for phase, im in frames.items():
        canvas = im
        out = ASSETS / f'fish-{phase}.png'
        files = {'sprite': write_asset(canvas, out)}
        sprites[phase] = base64.b64encode(out.read_bytes()).decode('ascii')
        for suffix, sz, fit in [('-icon', (128, 128), (116, 116)), ('-side', (160, 192), (144, 176))]:
            small = canvas.copy()
            small.thumbnail(fit, Image.Resampling.LANCZOS)
            square = Image.new('RGBA', sz)
            square.alpha_composite(small, ((sz[0] - small.width) // 2, (sz[1] - small.height) // 2))
            target = ASSETS / f'fish-{phase}{suffix}.png'
            files[suffix] = write_asset(square, target)
            if suffix == '-icon':
                icons[phase] = base64.b64encode(target.read_bytes()).decode('ascii')
        manifest['states'][phase] = {
            'source': f'outputs/whale-it-states/frames-seated/{phase}-384.png',
            'sourceSha256': digest(FRAMES / f'{phase}-384.png'),
            'normalizedBounds': list(canvas.getchannel('A').getbbox()),
            'files': files,
        }

    # Keep the expanded-state block: this script only owns the seated states.
    existing = ASSETS / 'artwork.json'
    if existing.exists():
        old = json.loads(existing.read_text(encoding='utf8'))
        if 'buddy' in old:
            manifest['buddy'] = old['buddy']

    icon = Image.new('RGBA', (256, 256))
    figure = Image.open(ASSETS / 'fish-idle.png').convert('RGBA')
    figure.thumbnail((232, 232), Image.Resampling.LANCZOS)
    icon.alpha_composite(figure, ((256 - figure.width) // 2, (256 - figure.height) // 2))
    icon.save(ROOT / 'icon.png', optimize=True)
    encoded = base64.b64encode((ROOT / 'icon.png').read_bytes()).decode('ascii')
    (ROOT / 'icon.svg').write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" role="img" aria-label="鲸哨">'
        '<image width="256" height="256" href="data:image/png;base64,' + encoded + '"/></svg>\n',
        encoding='utf8')
    (ASSETS / 'artwork.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf8')

    client = ROOT / 'client.js'
    # Inline artwork is generated by scripts/build-client.mjs from assets/ and
    # artwork.json. Do not rewrite client.js here: two generators would fight.
    print(json.dumps({
        'artwork': ID,
        'clientBytes': client.stat().st_size,
        'iconBytes': (ROOT / 'icon.png').stat().st_size,
        'runtimeAssetsBytes': sum(f['bytes'] for s in manifest['states'].values() for f in s['files'].values()),
    }, ensure_ascii=False))


if __name__ == '__main__':
    main()
